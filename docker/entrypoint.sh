#!/bin/bash
#
# End-to-end TPC-DS reproduction inside the container.
#
#   build dsdgen -> generate data -> init MariaDB at PAGE_SIZE -> load ->
#   index -> ANALYZE -> benchmark (baseline and/or tuned) -> write results
#
# The project is mounted READ-ONLY at /project.  Everything written goes to
# /data (scratch, discarded) and /results (bind-mounted to the host).
set -Eeuo pipefail

PROJECT=/project
DATA=/data
RESULTS=/results
DATADIR=$DATA/mysql
DSDATA=$DATA/tpcds-data
SOCK=$DATA/mysql.sock

say() { printf '\n\033[1m[%s] %s\033[0m\n' "$(date +%H:%M:%S)" "$*"; }
note() { printf '          %s\n' "$*"; }

# ---------------------------------------------------------------- profiles
# Use the same defaults and validation as reproduce.sh, including direct
# docker run invocations. The wrapper forwards its fully resolved settings.
PROFILE="${PROFILE:-quick}"
. "$(dirname "$0")/profiles.sh"
tpcds_profile_defaults
tpcds_validate_config
MEMORY_BLOCK=$(tpcds_memory_cnf)

# QUERYSET picks the SQL, TUNED picks the server settings.  They are separate
# knobs that happen to share the word "tuned", so the banner spells both out.
case "$QUERYSET" in
  tuned)  QS_DESC="queries/tuned/ — 40 tier-4/5, optimized where one exists" ;;
  tier45) QS_DESC="40 tier-4/5, adapted TPC-DS text, unoptimized" ;;
  all)    QS_DESC="all 99, adapted TPC-DS text, unoptimized" ;;
  smoke)  QS_DESC="four adapted queries (3, 12, 18, 76) — functional check only" ;;
esac

say "TPC-DS on MariaDB — reproduction run"
note "profile       $PROFILE"
note "scale factor  $SCALE   (dsdgen -RNGSEED $RNGSEED)"
note "page size     ${PAGE_SIZE}K"
note "buffer pool   $BUFFER_POOL"
note "sample pages  $SAMPLE_PAGES"
note "query set     $QUERYSET  ($QS_DESC)"
note "server config $TUNED"
if [[ "$PROFILE" == smoke ]]; then
  note "smoke limits  Aria=$ARIA_PAGECACHE_BUFFER_SIZE, temp=$TMP_TABLE_SIZE, sort=$SORT_BUFFER_SIZE, joins=$JOIN_BUFFER_SPACE_LIMIT"
  note "purpose       functional check; timings are not reference benchmark results"
fi
note "mariadb       $(mariadbd --version | head -1)"
note "cpus          $(nproc)   memory  $(free -g | awk '/^Mem:/{print $2}')G"

[[ -d "$PROJECT/sql" ]] || { echo "ERROR: /project does not look like the repo (no sql/)" >&2; exit 1; }

# queries/tuned/ is generated by queries/build-tuned.py and committed, so a
# clone has it.  It cannot be regenerated here: /project is mounted read-only.
if [[ "$QUERYSET" == tuned ]]; then
  n=$(ls "$PROJECT"/queries/tuned/query*.sql 2>/dev/null | wc -l)
  if [[ "$n" -eq 0 ]]; then
    echo "ERROR: QUERYSET=tuned but /project/queries/tuned/ is empty." >&2
    echo "       Run 'python3 queries/build-tuned.py' on the host first," >&2
    echo "       or use -e QUERYSET=tier45 for the unoptimized queries." >&2
    exit 1
  fi
  note "tuned files   $n found"
fi
mkdir -p "$DSDATA" "$RESULTS"

# ---------------------------------------------------------------- 1. dsdgen
say "1/7  Building dsdgen"
BUILD=$DATA/tools
rm -rf "$BUILD"; mkdir -p "$BUILD"
cp -r "$PROJECT"/DSGen-software-code-4.0.0/tools/. "$BUILD"/
# The committed makefile targets macOS; Linux needs OS=LINUX, which selects
# gcc, lex, yacc and the LINUX block in config.h.
sed -i 's/^OS[[:space:]]*=.*/OS = LINUX/' "$BUILD/makefile"

# The TPC-DS v4.0.0 sources are C89-era and do not compile with a modern gcc
# as-is.  Two separate problems, both hit when the base image moved from
# Ubuntu 24.04 (gcc 13) to 26.04 (gcc 15) along with MariaDB 13.0.2:
#
#   * gcc 15 defaults to C23, which REMOVED K&R function definitions.
#     date.c:570 is one: getDateWeightFromJulian(jDay, nDistribution) with
#     the parameter types declared on the following lines.  -std=gnu17 keeps
#     them legal (deprecated, but accepted).
#   * gcc 14 promoted implicit-int, implicit-function-declaration,
#     int-conversion, incompatible-pointer-types and return-mismatch from
#     warnings to errors.  The toolkit trips several; demote them again.
#
# -fcommon was already in the makefile for the same class of reason (gcc 10
# made -fno-common the default).  Nothing here changes generated data: these
# are diagnostics settings, not code generation.
sed -i 's|^LINUX_CFLAGS\(.*\)$|LINUX_CFLAGS\1 -std=gnu17 -Wno-error=implicit-int -Wno-error=implicit-function-declaration -Wno-error=int-conversion -Wno-error=incompatible-pointer-types -Wno-error=return-mismatch|' \
    "$BUILD/makefile"
( cd "$BUILD" && make -s dsdgen 2>&1 | tail -5 ) || {
  echo "ERROR: dsdgen build failed" >&2; exit 1; }
[[ -x "$BUILD/dsdgen" ]] || { echo "ERROR: dsdgen not produced" >&2; exit 1; }
note "built $("$BUILD/dsdgen" 2>&1 | head -1 || true)"

# ---------------------------------------------------------------- 2. data
say "2/7  Generating scale-factor-$SCALE data"

# Same hazard as the datadir's page size, and worse because it is silent:
# the .dat files carry no record of the scale factor they were generated at,
# so "data already present" would reuse SF=1 files for a run that announces
# SF=4 and writes SF=4 into every result file.  A marker makes the scale
# explicit, and a mismatch regenerates and forces stage 4 to reload.
# The seed matters as much as the scale.  dsdgen without -RNGSEED produces a
# different dataset from the one every result in this repository was measured
# on (report/00-overview.md generates with -RNGSEED 10), so the container was
# reproducing the *method* but not the *answers*: a side-by-side check of
# SF=1 results found 36 of 40 queries disagreeing, with row counts like q4
# 8 against 6 and q31 56 against 44.  Nothing was wrong with either run; they
# were simply different databases.
SCMARK=$DSDATA/.scale
WANT="$SCALE:$RNGSEED"
RELOAD=0
if [[ -f "$DSDATA/store_sales.dat" ]]; then
  had=$(cat "$SCMARK" 2>/dev/null || echo unknown)
  if [[ "$had" != "$WANT" ]]; then
    if [[ "$had" == unknown ]]; then
      note "data predates the scale/seed marker; regenerating to be sure"
    else
      note "data on disk is scale:seed $had, need $WANT -- regenerating"
    fi
    rm -f "$DSDATA"/*.dat "$SCMARK"
    RELOAD=1
  fi
fi

if [[ -f "$DSDATA/store_sales.dat" ]]; then
  note "scale-factor-$SCALE data already present, skipping"
else
  # No -TERMINATE N: it drops the trailing '|' from each line, and
  # sql/04_load_data.sql reads these files with LINES TERMINATED BY '|\n'.
  ( cd "$BUILD" && ./dsdgen -SCALE "$SCALE" -RNGSEED "$RNGSEED" \
                          -DIR "$DSDATA" -FORCE ) \
    2>&1 | grep -vi 'warning' | tail -3 || true
  [[ -f "$DSDATA/store_sales.dat" ]] || { echo "ERROR: no data generated" >&2; exit 1; }
  echo "$WANT" > "$SCMARK"
  RELOAD=1
fi
note "$(du -sh "$DSDATA" | cut -f1) across $(ls "$DSDATA"/*.dat | wc -l) files"
chown -R mysql:mysql "$DSDATA"

# ---------------------------------------------------------------- 3. server
write_cnf() {   # $1 = extra settings block
  local memory=""
  # Apply the small limits during setup as well as during query execution.
  [[ "$PROFILE" != smoke ]] || memory="$MEMORY_BLOCK"
  cat > "$DATA/my.cnf" <<EOF
[mysqld]
datadir                        = $DATADIR
socket                         = $SOCK
skip-networking
user                           = mysql
pid-file                       = $DATA/mysqld.pid
log-error                      = $DATA/mysqld.err

innodb_page_size               = ${PAGE_SIZE}K
innodb_buffer_pool_size        = $BUFFER_POOL
innodb_stats_persistent_sample_pages = $SAMPLE_PAGES

userstat                       = 1
innodb_flush_log_at_trx_commit = 1
innodb_flush_method            = O_DIRECT
innodb_file_per_table          = ON
innodb_adaptive_hash_index     = OFF
character_set_server           = utf8mb4
collation_server               = utf8mb4_general_ci
local_infile                   = 1
secure_file_priv               =

# Pinned to match pagesize/my-32k-sf4-t1exact.cnf, the instance every
# published figure was measured on.  These were previously left at MariaDB's
# defaults: the defaults happened to agree, but "happens to agree" is not
# reproducible -- a future release changing one of them would silently move
# the numbers.
innodb_log_file_size           = 96M
innodb_io_capacity             = 200
innodb_write_io_threads        = 4
innodb_doublewrite             = ON
skip_name_resolve
# Keep setup/load allowance independent of the smoke query deadline.
max_statement_time             = 3600
$memory
$1
EOF
}

start_server() {
  mariadbd --defaults-file="$DATA/my.cnf" >>"$DATA/mysqld.err" 2>&1 &
  for _ in $(seq 1 300); do
    mariadb-admin --socket="$SOCK" -u root ping >/dev/null 2>&1 && return 0
    sleep 1
  done
  echo "ERROR: server did not start; last log lines:" >&2
  tail -20 "$DATA/mysqld.err" >&2
  return 1
}

stop_server() {
  mariadb-admin --socket="$SOCK" -u root ping >/dev/null 2>&1 || return 0
  mariadb-admin --socket="$SOCK" -u root shutdown
  for _ in $(seq 1 300); do
    mariadb-admin --socket="$SOCK" -u root ping >/dev/null 2>&1 || return 0
    sleep 1
  done
  return 1
}

say "3/7  Initialising MariaDB with ${PAGE_SIZE}K pages"

# innodb_page_size is fixed when the datadir is created and cannot be changed
# afterwards.  Reusing a datadir built at a different page size fails deep
# inside InnoDB startup --
#
#   [ERROR] InnoDB: Data file './ibdata1' uses page size 16384, but the
#           innodb_page_size start-up parameter is 32768
#
# -- which cost five minutes of start_server's retry loop before anything
# said why.  A marker file records what the datadir was built with, so a
# mismatch is caught instantly and repaired by rebuilding it.  That is safe:
# the datadir is a cache, and the generated .dat files it loads from live at
# $DSDATA, outside it.  Stage 4 reloads automatically.
# The marker also carries the server version.  A datadir written by one major
# MariaDB release is not safely reused by another -- the image was moved from
# 11.4 to 13.0.2 to match the macOS host, and a 11.4 datadir left in the
# volume would otherwise be handed to a 13.0.2 server.
PSMARK=$DATADIR/.innodb_page_size
SRVVER=$(mariadbd --version | grep -oE '[0-9]+\.[0-9]+\.[0-9]+' | head -1)
WANT_DD="${PAGE_SIZE}:${SRVVER}"
if [[ -d "$DATADIR/mysql" ]]; then
  had=$(cat "$PSMARK" 2>/dev/null || echo unknown)
  if [[ "$had" == "$WANT_DD" ]]; then
    note "datadir already initialised at ${PAGE_SIZE}K by $SRVVER, reusing"
  else
    if [[ "$had" == unknown ]]; then
      note "datadir predates the page-size/version marker; rebuilding to be sure"
    else
      note "datadir is page:version $had, need $WANT_DD -- rebuilding"
    fi
    note "(the generated data under $DSDATA is kept; only the database is rebuilt)"
    rm -rf "$DATADIR"
  fi
fi

if [[ -d "$DATADIR/mysql" ]]; then
  write_cnf ""
else
  write_cnf ""
  mariadb-install-db --defaults-file="$DATA/my.cnf" --user=mysql \
      --datadir="$DATADIR" --auth-root-authentication-method=normal \
      >"$DATA/install.log" 2>&1 || { tail -20 "$DATA/install.log" >&2; exit 1; }
  echo "$WANT_DD" > "$PSMARK"
fi
chown -R mysql:mysql "$DATA"
start_server
ACTUAL=$(mariadb --socket="$SOCK" -u root -N -B -e "select @@innodb_page_size/1024")
[[ "${ACTUAL%.*}" == "$PAGE_SIZE" ]] || {
  echo "ERROR: page size is ${ACTUAL%.*}K, expected ${PAGE_SIZE}K" >&2; exit 1; }
note "running, innodb_page_size = ${PAGE_SIZE}K"

CLI="mariadb --socket=$SOCK -u root"

# ---------------------------------------------------------------- 4. load
say "4/7  Creating schema and loading data"
# Require the expected tables to be PRESENT, rather than the schema to hold
# exactly 25 tables.  Two scratch tables left in tpcds by an experiment made
# that count 27, which read as a broken database and silently dropped and
# reloaded 32 GB of it.
WANT_TBLS=$(grep -ioE '^CREATE TABLE (IF NOT EXISTS )?[a-z0-9_]+' "$PROJECT/sql/01_schema.sql" \
            | awk '{print tolower($NF)}' | sort -u)
HAVE_TBLS=$($CLI -N -B -e "select lower(table_name) from information_schema.tables where table_schema='tpcds'" 2>/dev/null | sort -u)
MISSING=$(comm -23 <(printf '%s\n' "$WANT_TBLS") <(printf '%s\n' "$HAVE_TBLS") | wc -l | tr -d ' ')
if (( RELOAD == 0 )) && (( MISSING == 0 )); then
  note "tpcds already has the 25 expected tables, skipping"
else
  (( RELOAD == 0 )) || note "data was regenerated, so the database is reloaded"
  $CLI -e "drop database if exists tpcds; create database tpcds"
  $CLI tpcds < "$PROJECT/sql/01_schema.sql"
  t0=$SECONDS
  # the loader's paths are relative to the repo root; point them at /data
  sed "s#DSGen-software-code-4.0.0/data/#$DSDATA/#" "$PROJECT/sql/04_load_data.sql" \
    | $CLI --local-infile=1 tpcds
  note "loaded in $((SECONDS-t0))s"
fi

# A format mismatch makes LOAD DATA insert nothing without failing, which
# then looks like a benchmark where every query is instant and returns no
# rows.  Fail here instead.
ROWS=$($CLI -N -B -e "select count(*) from tpcds.store_sales")
if (( ROWS < 1000 )); then
  echo "ERROR: store_sales has $ROWS rows after loading -- the data did not load." >&2
  echo "       Check that the .dat lines end with '|' (dsdgen without -TERMINATE N)." >&2
  $CLI -N -B -e "show warnings" 2>/dev/null | head -5 >&2
  exit 1
fi
note "store_sales: $(printf "%'d" "$ROWS") rows"
note "$($CLI -N -B -e "select concat(format(sum(table_rows),0),' rows, ',round(sum(data_length+index_length)/1073741824,1),' GB') from information_schema.tables where table_schema='tpcds'")"

# ---------------------------------------------------------------- 5. indexes
say "5/7  Creating indexes"

if [[ "$PROFILE" == smoke ]]; then
  note "smoke skips secondary-index creation and pruning (dedicated volume by default)"
else

# DEFAULT: the full historical set (sql/05, 11, 14).  It is the fastest
# configuration measured at SF=4 by a wide margin: 735.2-805.8s in the
# container against 1487.0s when the 129 unread indexes were dropped.
# (491.4s also appears in older notes -- that was the macOS host, not this
# container, and the two are not comparable.)
#
# That regression is the finding, not a mishap.  "This index was read" and
# "the optimizer needs this index to cost a good plan" are different things.
# The read counters were taken with all 166 present; remove 129 and the cost
# estimates move, so the plans move.  7 of the 37 supposedly-useful indexes
# stopped being read afterwards -- proof the plans changed rather than just
# the storage.
#
# KEPT_INDEXES=1 builds only the 37 read indexes (101.7s at SF=1, 1487.0s at
# SF=4).  IGNORE_UNUSED=1 hides the 129 from the optimizer without dropping
# them, which is how we separate "unused at execution" from "unused for
# planning" -- see report/27.
KEPT="$PROJECT/sql/indexes_kept.sql"
if [[ "${KEPT_INDEXES:-0}" != "1" || ! -f "$KEPT" ]]; then
  # Count the definitions rather than hardcoding a number.  167 was wrong:
  # the three files hold 173 CREATE INDEX statements but only 164 distinct
  # (table, index) pairs -- nine indexes are defined twice, once in 05/11 and
  # again in 14_contributed.  A database with the full set has 166 secondary
  # indexes, so the hardcoded 167 was never reached and every `full` run
  # re-ran all 173 statements to discover they already existed.
  # This counts single-line definitions only, so it is a lower bound -- which
  # is the right semantics here, because it is only a "do we need to build?"
  # trigger and the build itself is CREATE INDEX IF NOT EXISTS either way.
  WANT_IDX=$(cat "$PROJECT"/sql/05_indexes.sql \
                 "$PROJECT"/sql/11_optimizer_indexes.sql \
                 "$PROJECT"/sql/14_contributed_indexes.sql 2>/dev/null \
             | grep -ioE '^CREATE +(UNIQUE +)?INDEX +[a-z0-9_]+ +ON +[a-z0-9_]+' \
             | tr 'A-Z' 'a-z' \
             | sed -E 's/^create +(unique +)?index +([a-z0-9_]+) +on +([a-z0-9_]+)$/\3 \2/' \
             | sort -u | wc -l | tr -d ' ')
  SRC="the full historical set (sql/05, 11, 14)"
else
  WANT_IDX=$(grep -ciE '^CREATE +(UNIQUE +)?INDEX' "$KEPT" || echo 0)
  SRC="sql/indexes_kept.sql"
fi
HAVE_IDX=$($CLI -N -B -e "select count(*) from (select distinct table_name,index_name from information_schema.statistics where table_schema='tpcds' and index_name<>'PRIMARY') x")

if (( HAVE_IDX > WANT_IDX )) && [[ "$SRC" == "sql/indexes_kept.sql" ]]; then
  # The database carries more indexes than the kept set -- an older volume
  # built with the full set. Converge on the target rather
  # than leaving a mixture, so the index set depends on the configuration
  # and not on the order someone happened to run things in.
  note "has $HAVE_IDX secondary indexes, target is $WANT_IDX -- dropping the rest"
  $CLI tpcds < "$PROJECT/sql/drop_unused_indexes.sql"
  $CLI tpcds < "$KEPT"
  note "now $($CLI -N -B -e "select count(*) from (select distinct table_name,index_name from information_schema.statistics where table_schema='tpcds' and index_name<>'PRIMARY') x") secondary"
elif (( HAVE_IDX >= WANT_IDX )); then
  note "already has $HAVE_IDX secondary indexes, skipping"
else
  note "building $SRC"
  t0=$SECONDS
  if [[ "$SRC" == "sql/indexes_kept.sql" ]]; then
    $CLI tpcds < "$KEPT"
  else
    for f in 05_indexes 11_optimizer_indexes 14_contributed_indexes; do
      [[ -f "$PROJECT/sql/$f.sql" ]] || continue
      sed 's/^CREATE INDEX /CREATE INDEX IF NOT EXISTS /i' "$PROJECT/sql/$f.sql" | $CLI tpcds
    done
  fi
  note "built in $((SECONDS-t0))s"
fi
note "$($CLI -N -B -e "select concat(count(distinct table_name,index_name),' indexes total') from information_schema.statistics where table_schema='tpcds'")"

# IGNORE_UNUSED=1 hides the never-read indexes from the optimizer while
# leaving them on disk and maintained.  This is the controlled half of the
# experiment: dropping them made SF=4 three times slower, and ignoring them
# tells us whether that was the optimizer losing information it needed to
# plan, or simply 16.3 GB of storage getting out of the way.
#
#   ignored as slow as dropped      -> the optimizer needed them to PLAN
#   ignored as fast as the full set -> the cost was STORAGE, not planning
#
# Metadata only, so it costs a statement per index and no rebuild.
# IGNORE_SQL names which list to hide, relative to sql/.  The default list
# is the never-READ one; sql/ignore_unreferenced_indexes.sql is the stricter
# and correct one -- indexes no plan at any scale factor even mentions.
IGN="$PROJECT/sql/${IGNORE_SQL:-ignore_unused_indexes.sql}"
# Clear every IGNORED flag first, generated from the database rather than
# read from a static list.  sql/unignore_all_indexes.sql went stale the
# moment the index set changed: two of its names no longer existed, the
# client stopped at the first missing one, and `|| true` swallowed it -- so
# 48 indexes stayed hidden through a run labelled "everything visible", and
# the A/B it was measuring compared 70 hidden against 48 hidden.
clear_ignored() {
  local n
  n=$($CLI -N -B -e "select count(distinct table_name,index_name) from information_schema.statistics where table_schema='tpcds' and ignored='YES'")
  (( n == 0 )) && return 0
  $CLI -N -B -e "select concat('ALTER TABLE ',table_name,' ALTER INDEX ',index_name,' NOT IGNORED;')
                   from (select distinct table_name,index_name from information_schema.statistics
                          where table_schema='tpcds' and ignored='YES') x" | $CLI tpcds
  note "cleared $n leftover IGNORED index(es)"
}
clear_ignored

if [[ "${IGNORE_UNUSED:-0}" == "1" && -f "$IGN" ]]; then
  $CLI tpcds < "$IGN"
  # count(*) over information_schema.statistics counts one row per COLUMN,
  # so a 3-column index counted 3 times and the note read "ignored 166"
  # for a 129-index file.  Count distinct indexes.
  n=$($CLI -N -B -e "select count(distinct table_name,index_name) from information_schema.statistics where table_schema='tpcds' and ignored='YES'")
  note "ignored $n indexes from $(basename "$IGN") (still on disk, invisible to the optimizer)"
  # Assert it, rather than trusting it.  An ignore list naming an index that
  # no longer exists leaves the rest of the file unapplied.
  want=$(grep -ci '^ALTER TABLE' "$IGN" || echo 0)
  if (( n != want )); then
    echo "ERROR: $(basename "$IGN") has $want statements but $n indexes are IGNORED." >&2
    echo "       The list is stale -- regenerate it with scripts/decide-indexes.py." >&2
    exit 1
  fi
else
  # Nothing hidden: confirm it, so a run labelled "full set" really is one.
  n=$($CLI -N -B -e "select count(distinct table_name,index_name) from information_schema.statistics where table_schema='tpcds' and ignored='YES'")
  (( n == 0 )) || { echo "ERROR: $n indexes are still IGNORED in a full-set run." >&2; exit 1; }
fi

# Still available for a database that already has the full set: drop the
# unused ones in place rather than rebuilding.
if [[ "${PRUNE_INDEXES:-0}" == "1" && -f "$PROJECT/sql/drop_unused_indexes.sql" ]]; then
  before=$($CLI -N -B -e "select count(distinct table_name,index_name) from information_schema.statistics where table_schema='tpcds'")
  $CLI tpcds < "$PROJECT/sql/drop_unused_indexes.sql"
  after=$($CLI -N -B -e "select count(distinct table_name,index_name) from information_schema.statistics where table_schema='tpcds'")
  note "pruned unused indexes: $before -> $after"
fi
fi  # reference-profile index setup

say "6/7  Refreshing optimizer statistics"
TBLS=$($CLI -N -B -e "select group_concat(table_name) from information_schema.tables where table_schema='tpcds'")
$CLI tpcds -e "analyze table $TBLS" >/dev/null
note "done"

# ---------------------------------------------------------------- 7. benchmark
say "7/7  Benchmarking"

# Zero the index read counters here, so whatever INDEX_STATISTICS reports
# afterwards covers exactly the benchmark and not the loading, indexing and
# ANALYZE that preceded it.  Costs nothing and makes the usage report a
# by-product of any run rather than a second pass over the suite.
$CLI -e "FLUSH INDEX_STATISTICS" >/dev/null 2>&1 || \
  note "could not flush INDEX_STATISTICS (userstat off?); usage report will be skipped"
# Prove the live server matches sql/tpcds-tuned.cnf -- the standing
# configuration every published figure was measured on -- rather than
# assuming the cnf block was written correctly and applied.  A setting that
# silently failed to take would otherwise be invisible until someone noticed
# the numbers were wrong.
check_settings() {
  [[ -f "$PROJECT/sql/tpcds-tuned.cnf" ]] || return 0
  $CLI -N -B -e "select 1" >/dev/null 2>&1 || return 0
  python3 - "$PROJECT/sql/tpcds-tuned.cnf" "$SOCK" <<'PY'
import subprocess, sys, re
cnf, sock = sys.argv[1], sys.argv[2]
def to_bytes(v):
    m = re.fullmatch(r'(\d+)([KMG]?)', v.strip().upper())
    if not m: return None
    return int(m.group(1)) * {'':1, 'K':1024, 'M':1024**2, 'G':1024**3}[m.group(2)]
want = {}
for line in open(cnf):
    line = line.split('#')[0].strip()
    if '=' not in line or line.startswith('['): continue
    k, v = (x.strip() for x in line.split('=', 1))
    want[k] = v.strip("'\"")
q = subprocess.run(['mariadb', f'--socket={sock}', '-u', 'root', '-N', '-B',
                    '-e', "show variables"], capture_output=True, text=True)
have = dict(l.split('\t', 1) for l in q.stdout.strip().splitlines() if '\t' in l)
bad = []
for k, v in sorted(want.items()):
    got = have.get(k)
    if got is None:
        bad.append((k, v, "not a variable here")); continue
    wb, gb = to_bytes(v), to_bytes(got)
    if wb is not None and gb is not None:
        ok = wb == gb
    elif ',' in v and '=' in v:
        # Flag sets like optimizer_switch: the server reports all 40 flags,
        # so comparing the whole string can never match.  Check that each
        # flag we asked for is present with the value we asked for.
        have_flags = dict(f.split('=', 1) for f in got.split(',') if '=' in f)
        ok = all(have_flags.get(f.split('=')[0]) == f.split('=')[1]
                 for f in v.split(',') if '=' in f)
        got = "flags present" if ok else got[:120] + "..."
    else:
        ok = got.strip("'\"") == v
    if not ok:
        bad.append((k, v, got))
print(f"          standing config: {len(want)-len(bad)}/{len(want)} settings match")
for k, v, got in bad:
    print(f"            DIFFERS  {k}: want {v}, have {got}")
PY
}

run_one() {   # $1 = tag, $2 = extra cnf block
  stop_server
  write_cnf "$2
max_statement_time = $STATEMENT_TIMEOUT"
  chown mysql:mysql "$DATA/my.cnf"
  start_server
  if [[ "$PROFILE" == smoke ]]; then
    note "smoke uses separate memory limits; the standing reference configuration does not apply"
  elif [[ -n "$2" ]]; then
    check_settings
  fi
  RNGSEED="$RNGSEED" SCALE="$SCALE" PROFILE="$PROFILE" STATEMENT_TIMEOUT="$STATEMENT_TIMEOUT" \
  python3 /usr/local/bin/bench.py "$SOCK" "$RESULTS/$1" "$1" "$QUERYSET" \
    | tee "$RESULTS/$1.log"
}

TUNING_BLOCK="$MEMORY_BLOCK
# The tuning that measured 2.90x at SF=4 (report 23).  Item 1 -- temp tables
# off a 16M default -- is about two thirds of it on its own.
innodb_read_io_threads         = 8
innodb_read_ahead_threshold    = 24
innodb_old_blocks_pct          = 25
join_cache_level               = 8
optimizer_switch               = 'mrr=on,mrr_cost_based=off'
key_buffer_size                = 16M
"

check_measured() {   # $1 = tag
  # Fast smoke queries are legitimate. Require complete successful artifacts,
  # rather than an arbitrary minimum runtime, for every profile.
  python3 /usr/local/bin/bench.py --check "$RESULTS/$1" "$QUERYSET"
}

# SKIP_BENCH=1 brings the database up under the measured configuration and
# stops short of running the 40 queries.  Used with KEEP_ALIVE=1 for the
# plan-stability work (report/27): comparing EXPLAIN output with an index
# visible against the same query with it IGNORED answers "does the optimizer
# consult this index?" deterministically, without paying 12 minutes of
# execution per index to find out.
if [[ "${SKIP_BENCH:-0}" == "1" ]]; then
  say "Benchmark skipped (SKIP_BENCH=1)"
  stop_server
  write_cnf "$TUNING_BLOCK
max_statement_time = $STATEMENT_TIMEOUT"
  chown mysql:mysql "$DATA/my.cnf"
  start_server
  [[ "$PROFILE" == smoke ]] || check_settings
else
case "$TUNED" in
  baseline) run_one baseline ""; check_measured baseline ;;   # stock: retired, kept for comparison
  tuned)    run_one tuned "$TUNING_BLOCK"; check_measured tuned ;;
  both)     run_one baseline ""; check_measured baseline
            run_one tuned "$TUNING_BLOCK"; check_measured tuned ;;
  *) echo "TUNED must be baseline, tuned or both (got $TUNED)" >&2; exit 1 ;;
esac
fi

# NOT here: INDEX_STATISTICS lives in memory, so shutting the server
# down discards every read counter.  The usage stage below needs them,
# so the server stays up until after it has been read.  This cost the
# index work its evidence: the stage ran, failed to connect, printed
# 'userstat is off', and sent the whole analysis to the macOS numbers.

# ---------------------------------------------------------------- report
# Index usage, as a by-product: the counters were zeroed just before the
# benchmark, so this is exactly what the query set read.  Written in the same
# shape as scripts/index-usefulness.sh produces on the host, so the analysis
# does not care which environment a report came from.
say "Index usage"
if $CLI -N -B -e "select @@userstat" 2>/dev/null | grep -qiE '^(1|ON)$'; then
  $CLI -B -N tpcds > "$RESULTS/index-usage-sf$SCALE.tsv" <<'SQL'
SELECT s.TABLE_NAME, s.INDEX_NAME,
       ROUND(IFNULL(z.stat_value,0) * @@innodb_page_size / 1048576, 1) AS mb,
       IFNULL(u.ROWS_READ, 0) AS rows_read,
       CASE WHEN s.IGNORED = 'YES'         THEN 'IGNORED'
            WHEN IFNULL(u.ROWS_READ,0) > 0 THEN 'used'
            ELSE 'UNUSED' END AS verdict
FROM (SELECT DISTINCT TABLE_SCHEMA, TABLE_NAME, INDEX_NAME, IGNORED
      FROM information_schema.STATISTICS WHERE TABLE_SCHEMA='tpcds') s
LEFT JOIN information_schema.INDEX_STATISTICS u
       ON u.TABLE_SCHEMA=s.TABLE_SCHEMA AND u.TABLE_NAME=s.TABLE_NAME
      AND u.INDEX_NAME=s.INDEX_NAME
LEFT JOIN mysql.innodb_index_stats z
       ON z.database_name=s.TABLE_SCHEMA AND z.table_name=s.TABLE_NAME
      AND z.index_name=s.INDEX_NAME AND z.stat_name='size'
ORDER BY verdict DESC, mb DESC, s.TABLE_NAME, s.INDEX_NAME;
SQL
  note "$(awk -F'\t' '$5=="UNUSED"{n++; m+=$3} END{printf "%d never read, %.1f GB", n, m/1024}' \
          "$RESULTS/index-usage-sf$SCALE.tsv")"
  note "wrote results/index-usage-sf$SCALE.tsv"
else
  # Say what it actually reported.  "userstat is off" was printed for every
  # run while userstat was on, because `select @@userstat` returns ON and the
  # test looked for 1 -- a silent failure that cost the index work its
  # evidence and sent it to the macOS numbers instead.
  note "no usage report: @@userstat = '$($CLI -N -B -e "select @@userstat" 2>&1 | head -1)'"
fi

# KEEP_ALIVE=1 leaves the server running and the container alive so the
# database can be queried from outside with `docker exec`.  Nothing in a
# normal run sets it; it exists for the index classification experiment,
# which needs hundreds of EXPLAINs against one loaded database and would
# otherwise pay a full startup for each.
if [[ "${KEEP_ALIVE:-0}" == "1" ]]; then
  say "KEEP_ALIVE=1 -- server left running on $SOCK"
  note "connect with: docker exec -it <container> mariadb --socket=$SOCK -u root tpcds"
  note "stop with:    docker stop <container>"
  trap 'stop_server' TERM INT
  # `wait` rather than `sleep infinity` so a docker stop reaches the trap and
  # the database is shut down cleanly instead of being killed mid-write.
  sleep infinity & wait $!
  exit 0
fi

stop_server

