#!/usr/bin/env python3
"""Render report/25-query-by-query.md from measured timings + 25-notes.json.

The report is ranked by SF=4 response time, so every re-run of the suite
reshuffles it.  Editing the markdown by hand is how it fell a whole
generation behind: at the point this generator was written, twenty of its
forty sections claimed "no optimized version exists" about a query that had
one.

So: ranks, times, totals and attributions come from the run; prose comes from
25-notes.json.  Edit the JSON (or report/seed-25-notes.py and re-run it),
never the generated markdown.

Also diffs each query's md5 against the previous run, if pagesize/results/
still holds one, and refuses to claim anything is verified if an answer moved.

Usage:  python3 report/gen-25.py [tag ...]

Tags are given largest scale factor first; the table is ranked by the first
one.  Defaults to the three-scale run: final-sf4 final-sf2 final-sf1.
"""
import json, os, sys, glob

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
RES = f"{REPO}/pagesize/results"
OUT = f"{HERE}/25-query-by-query.md"

TAGS = sys.argv[1:] or ["final-sf4", "final-sf2", "final-sf1"]


def scale_of(tag):
    """The scale factor a tag names, for column headings."""
    m = [c for c in tag.replace("-", " ").split() if c.lower().startswith("sf")]
    return m[-1][2:] if m else tag


def load(tag):
    """Accept a tag under pagesize/results, a container results directory, or
    a path.  The macOS instances were retired on 2026-10-26, so the canonical
    numbers now come from results/sf<N>/tuned; older pagesize/results/<tag>
    runs still load for historical comparison."""
    for cand in (tag,
                 f"{RES}/{tag}",
                 f"{REPO}/results/{tag}",
                 f"{REPO}/results/{tag}/tuned"):
        if glob.glob(f"{cand}/query*.json"):
            return {json.load(open(p))['query']: json.load(open(p))
                    for p in glob.glob(f"{cand}/query*.json")}
    return {}


PREAMBLE = """# The 40 tier-4/5 queries: what each optimization does

Response times measured on the standing configuration (`sql/tpcds-tuned.cnf`)
— 32K pages, 8 GB buffer pool, `innodb_stats_persistent_sample_pages=160` —
running `queries/tuned/`, which substitutes an optimized query where one
exists. Sorted by SF=4 response time, slowest first.

This file is generated by `report/gen-25.py` from the measured results and
`report/25-notes.json`. Edit those, not this.
"""

NEXT = """### What to look at next

1. **Decide on `idx_ss_date_store_profit`.** It exists but is left
   `IGNORED`, which is the state every figure in this table was measured in.
   Built for q77, it does nothing consistent for q77 — and makes **q70 ~2.9x**
   and **q5 ~2.4x** faster, reproducibly, with no consistent regression
   anywhere. It costs 512 MB, more than doubling `store_sales`'s index
   storage. Enable it with
   `ALTER TABLE store_sales ALTER INDEX idx_ss_date_store_profit NOT IGNORED;`
   and re-run this report. Detail in `report/26-the-last-eleven.md`.
2. **q67** — the slowest query that *is* optimized, and its gain is the
   smallest of the group at 1.3x.
3. **The eight from Nafiz** (q7, q8, q10, q11, q33, q37, q57, q74) were
   verified identical when wired in but never timed individually against the
   original. Their contribution is visible only in the suite total.
4. **q27** is still slower than the query it replaces (below).

### An optimization that makes things worse

| query | original | "optimized" |
|---|---:|---:|
| q27 | 5.2s | 6.4s |

It returns identical output, so it is correct — just slower than the query it
replaces at SF=4. Worth re-checking with its author, since it was tuned at
SF=1.

q97 used to sit here too, at 6.8s against 7.7s. That measurement was of the
version built on temporary tables; expressed as CTEs it is **1.92x faster**
than the original (7.3s → 3.8s). See its section above — including the NULL
bug that the rewrite introduced and that comparing `md5_sorted` against the
previous run caught.
"""

CAVEATS = """## Caveats

- Measured **in the Linux container** (`./run-scales.sh 1 4`), MariaDB
  13.0.2, 32K pages, 8 GB pool, data generated with `-RNGSEED 10`. The macOS
  instances were retired on 2026-10-26 once the container could do
  everything they were for; earlier editions of this table were measured
  there, where `innodb_flush_method=O_DIRECT` is accepted but has no effect,
  so absolute times are not comparable across the two.
- **One run each, and the whole table moves between runs.** This suite was
  run twice back to back on identical files and settings: **408.7s and
  475.4s**, a 16% spread on the total, with no change to anything measured.
  Individual queries swing further — q5 measured 32.2s and 60.0s in
  consecutive passes, q23's original spanned 160.7–213.0s over four, and q38
  (unchanged in both runs) measured 11.2s and 4.5s. Treat every figure here
  as indicative. The ordering is more reliable than any single row, and the
  per-query speedups quoted in the sections — interleaved A/B, best-of-3 —
  are more reliable than either.
- The per-query speedups quoted in the sections come from dedicated
  interleaved A/B runs, not from this table, so they will not divide out
  against these numbers.
- **q71's output order is not deterministic** (its ORDER BY is not a total
  order), which is why results are hashed both sorted and unsorted.
"""


def main():
    notes = {int(k): v for k, v in json.load(open(f"{HERE}/25-notes.json")).items()}
    runs = [(scale_of(t), load(t)) for t in TAGS]
    missing = [t for (sc, d), t in zip(runs, TAGS) if not d]
    if missing:
        sys.exit(f"no results for: {', '.join(missing)}")
    big, a = runs[0]                      # the scale the table is ranked by
    prev4 = load("baseline-c84451a-sf4")

    qs = sorted(a, key=lambda q: -a[q]['seconds'])
    totals = {sc: sum(d[q]['seconds'] for q in qs if q in d) for sc, d in runs}
    errs = [q for q in qs if a[q].get('status') != 'OK']

    # An answer that moved is a defect, not a result.  Report it loudly
    # rather than quietly publishing a faster number for a different query.
    # A scale factor does not identify a database, (scale, seed) does: if
    # several queries disagree on ROW COUNT the databases differ and no
    # answer comparison is meaningful.
    rowdiff = [q for q in qs if q in prev4
               and a[q].get('status') == 'OK' and prev4[q].get('status') == 'OK'
               and a[q].get('rows') != prev4[q].get('rows')]
    if len(rowdiff) > 1:
        moved, different_db = [], len(rowdiff)
    else:
        different_db = 0
        moved = [q for q in qs if q in prev4
                 and prev4[q].get('md5_sorted') and a[q].get('md5_sorted')
                 and prev4[q]['md5_sorted'] != a[q]['md5_sorted']]

    # No cross-scale answer comparison: a bigger database legitimately
    # returns different rows, so comparing md5 across scale factors flags all
    # 40 queries and means nothing.  What IS checked is each scale against a
    # previous run of the SAME scale, below.
    # Row counts usually grow with scale, so a drop is worth surfacing -- but
    # it is not by itself a defect.  q58 selects items whose revenue sits
    # within +/-10% across three channels and returns 0 rows at SF=1 and
    # SF=4 but 1 at SF=2: whether anything falls in that band is data
    # dependent and has no reason to be monotonic.
    shrank = []
    for q in qs:
        rows = [(sc, d[q].get('rows')) for sc, d in runs if q in d]
        rows = [(sc, r) for sc, r in rows if isinstance(r, int)]
        for (bs, br), (ss, sr) in zip(rows, rows[1:]):
            if br < sr:                    # runs are largest-first
                shrank.append(f"q{q} (SF={bs} {br} rows < SF={ss} {sr})")
                break

    L = [PREAMBLE]
    L.append("**Totals: "
             + ", ".join(f"SF={sc} {totals[sc]:.1f}s" for sc, _ in runs)
             + f".** {len(qs)}/{len(qs)} at every scale"
             + (", no errors.\n" if not errs else f", **{len(errs)} errors**: {errs}\n"))
    if shrank:
        L.append(f"> Note: {len(shrank)} query returns fewer rows at a larger "
                 f"scale factor — {'; '.join(shrank[:6])}. Usually worth a look, "
                 f"though not necessarily wrong: a query with a narrow filter "
                 f"band (q58 matches items whose revenue agrees within ±10% "
                 f"across three channels) has no reason to be monotonic in "
                 f"scale.\n" if len(shrank) == 1 else
                 f"> **{len(shrank)} queries return fewer rows at a larger scale "
                 f"factor: {'; '.join(shrank[:6])}.** Worth investigating.\n")
    if moved:
        L.append(f"> **Answers changed since the previous run: {moved}.** "
                 f"Investigate before trusting any figure below.\n")
    elif different_db:
        L.append(f"> Not compared against the older macOS baseline: "
                 f"{different_db} queries return a different number of rows, "
                 f"because that dataset was generated without `-RNGSEED 10` "
                 f"and is therefore a different database. Timings are "
                 f"comparable; answers are not.\n")

    small = runs[-1][0]
    hdr = "| # | query | " + " | ".join(f"SF={sc}" for sc, _ in runs) \
          + f" | SF{big}/SF{small} | optimized by |"
    L.append(hdr)
    L.append("|---|---|" + "---:|" * (len(runs) + 1) + "---|")
    # `is None` and not a truth test: q82 runs in 0.0s at SF=1, and treating
    # that as missing printed an em-dash for a query that did run.
    for i, q in enumerate(qs, 1):
        cells = []
        for sc, d in runs:
            v = d.get(q, {}).get('seconds')
            cells.append("—" if v is None else f"{v:.1f}s")
        lo = runs[-1][1].get(q, {}).get('seconds')
        r = f"{a[q]['seconds']/lo:.1f}x" if lo else "—"
        L.append(f"| {i} | q{q} | " + " | ".join(cells) + f" | {r} | "
                 f"{notes.get(q, {}).get('author') or '—'} |")

    L.append("\n---\n\n## Each query\n")
    for i, q in enumerate(qs, 1):
        per = ", ".join(f"{d[q]['seconds']:.1f}s at SF={sc}"
                        for sc, d in runs if q in d)
        L.append(f"### {i}. q{q} — {per}\n")
        L.append(notes.get(q, {}).get('body', "_No note recorded._") + "\n")

    t4 = totals[big]
    opt = [q for q in qs if notes.get(q, {}).get('author')]
    non = [q for q in qs if not notes.get(q, {}).get('author')]
    so = sum(a[q]['seconds'] for q in opt)
    sn = sum(a[q]['seconds'] for q in non)
    L.append("## Summary\n")
    L.append(f"### Where the SF={big} time goes\n")
    L.append(f"| | queries | SF={big} total | share |")
    L.append("|---|---:|---:|---:|")
    L.append(f"| optimized | {len(opt)} | {so:.1f}s | {so/t4*100:.0f}% |")
    L.append(f"| not optimized | {len(non)} | {sn:.1f}s | {sn/t4*100:.0f}% |")
    L.append(f"\nStill on the TPC-DS original: {', '.join('q%d' % q for q in non)}. "
             "Every one of those was rewritten and measured in "
             "`report/26-the-last-eleven.md`; none of those rewrites measured "
             "faster, so the original is what runs.\n")

    L.append(NEXT)

    # How the suite scales.  With three points the shape is visible: a query
    # whose cost grows faster than the data is losing its working set from
    # the buffer pool, and that shows up as a steepening between the steps,
    # not just a large end-to-end ratio.
    L.append(f"### How response time grows with the data\n")
    L.append("Totals, and the growth between each step:\n")
    L.append("| | " + " | ".join(f"SF={sc}" for sc, _ in reversed(runs)) + " |")
    L.append("|---|" + "---:|" * len(runs))
    L.append("| total | " + " | ".join(f"{totals[sc]:.1f}s"
                                       for sc, _ in reversed(runs)) + " |")
    growth = ["—"]
    rev = list(reversed(runs))
    for (p, _), (c, _) in zip(rev, rev[1:]):
        growth.append(f"{totals[c]/totals[p]:.2f}x" if totals[p] else "—")
    L.append("| vs previous | " + " | ".join(growth) + " |")
    L.append("\nThe data grows 2x at each step, so a total growing faster "
             "than 2x means the suite is degrading superlinearly.\n")

    L.append(f"### The SF={big} / SF={small} ratio\n")
    rat = sorted(((a[q]['seconds'] / runs[-1][1][q]['seconds'], q) for q in qs
                  if runs[-1][1].get(q, {}).get('seconds')), reverse=True)
    L.append("| query | ratio | |")
    L.append("|---|---:|---|")
    for r, q in rat[:5]:
        L.append(f"| q{q} | {r:.1f}x | {notes.get(q, {}).get('author') or 'not optimized'} |")
    r, q = rat[-1]
    L.append(f"| q{q} | **{r:.1f}x** | the flattest — scales best of the {len(rat)} |")
    L.append("\nA high ratio means the query degrades faster than the data "
             "grows, usually because its working set stops fitting in the "
             "buffer pool.\n")
    L.append(CAVEATS)

    open(OUT, 'w').write("\n".join(L) + "\n")
    print(f"wrote {OUT}")
    print("  " + str(len(qs)) + " queries   "
          + "   ".join(f"SF={sc} {totals[sc]:.1f}s" for sc, _ in runs))
    print(f"  optimized {len(opt)} ({so:.1f}s)   on the original {len(non)} ({sn:.1f}s)")
    if shrank:
        print(f"  !! fewer rows at a larger scale: {shrank}")
    if moved:
        print(f"  !! answers changed vs previous run: {moved}")
    if errs:
        print(f"  !! errors: {errs}")


if __name__ == '__main__':
    main()
