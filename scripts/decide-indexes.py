#!/usr/bin/env python3
"""Decide which indexes to drop, from evidence at every scale factor.

    python3 scripts/decide-indexes.py analysis/index-consulted-sf*.tsv

Takes the per-scale classifications written by scripts/index-consulted.py and
keeps an index if ANY scale factor has a reason to keep it:

    read during execution at any scale            -> keep
    mentioned in any plan at any scale            -> keep
    neither, at every scale measured              -> drop

The second rule is the one that matters.  An index can be read by nothing and
still be weighed by the optimizer when it costs alternatives; remove it and
the costing changes, so the plan changes.  Dropping the 129 indexes that no
scale factor READ made SF=4 twice as slow.  "Never read" was the wrong test.

Writes:
    sql/drop_unreferenced_indexes.sql     the drops
    sql/ignore_unreferenced_indexes.sql   the same set, hidden not dropped
    sql/unignore_all_indexes.sql          make everything visible again
    analysis/index-decisions.md           the table, with reasons
"""
import glob, os, re, sys
from collections import defaultdict

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main(paths):
    if not paths:
        paths = sorted(glob.glob(f"{REPO}/analysis/index-consulted-sf*.tsv"))
    if not paths:
        sys.exit("no analysis/index-consulted-sf*.tsv -- run index-consulted.py first")

    size, read, seen = {}, defaultdict(int), defaultdict(dict)
    for p in paths:
        scale = re.search(r"sf(\d+)", os.path.basename(p)).group(1)
        for line in list(open(p))[1:]:
            f = line.rstrip("\n").split("\t")
            if len(f) < 6:
                continue
            tbl, name, mb, rows, verdict, qs = f[0], f[1], float(f[2]), int(f[3]), f[4], f[5]
            key = (tbl, name)
            size[key] = max(size.get(key, 0.0), mb)
            read[key] = max(read[key], rows)
            seen[key][scale] = (verdict, [q for q in qs.split(",") if q])
    scales = sorted({s for v in seen.values() for s in v}, key=int)
    print(f"  {len(seen)} secondary indexes, scale factors {', '.join(scales)}")
    for p in paths:
        print(f"    {os.path.relpath(p, REPO)}")

    # An index measured HARMFUL is dropped whatever else is true of it: it is
    # weighed by the optimizer, and weighed into a worse plan.  idx_inv_date_sk
    # is never read, appears in six queries' possible_keys, and makes query22
    # run 38.4s instead of 10.6s.  See scripts/index-harm-scan.py.
    harmful = {}
    hp = f"{REPO}/analysis/index-harm-sf4.tsv"
    if os.path.exists(hp):
        for line in list(open(hp))[1:]:
            f = line.rstrip("\n").split("\t")
            if len(f) >= 7 and f[6].startswith("HARMFUL"):
                harmful[(f[0], f[1])] = (float(f[4]), float(f[5]))
    if harmful:
        print(f"  {len(harmful)} index(es) measured harmful; dropping regardless of plan use")

    keep, drop = [], []
    for key in sorted(seen, key=lambda k: (-size.get(k, 0), k)):
        per = seen[key]
        why = []
        if key in harmful:
            a, b = harmful[key]
            print(f"    {key[1]} on {key[0]}: {a:.1f}s -> {b:.1f}s when hidden")
            drop.append((key, [f"HARMFUL: {a:.1f}s -> {b:.1f}s when hidden"], per))
            continue
        if read[key] > 0:
            why.append(f"read {read[key]:,} rows")
        for s in scales:
            v, qs = per.get(s, ("(not measured)", []))
            if v == "considered":
                why.append(f"SF={s} plans weigh it ({len(qs)} queries)")
            elif v == "(not measured)":
                why.append(f"SF={s} not measured")
        (keep if why else drop).append((key, why, per))

    os.makedirs(f"{REPO}/analysis", exist_ok=True)
    gb = lambda rows: sum(size.get(k, 0) for k, *_ in rows) / 1024
    print(f"\n  keep {len(keep)} indexes ({gb(keep):.2f} GB)")
    print(f"  drop {len(drop)} indexes ({gb(drop):.2f} GB)")

    head = """-- {title}
--
-- Generated by scripts/decide-indexes.py from {src}.
-- {n} indexes that, at every scale factor measured ({sc}), were neither read
-- while executing nor mentioned in any query plan.  The optimizer never
-- considered them, so removing them cannot change which plan is chosen.
--
-- This is NOT the same as "never read".  {nk} further indexes are never read
-- but DO appear in plans as alternatives the optimizer weighs; those are kept.
-- Dropping on the never-read test alone made SF=4 twice as slow.
"""
    for fname, stmt, title in (
            ("drop_unreferenced_indexes.sql", "DROP INDEX IF EXISTS {i} ON {t};",
             "Drop the indexes no plan at any scale factor mentions"),
            ("ignore_unreferenced_indexes.sql",
             "ALTER TABLE {t} ALTER INDEX {i} IGNORED;",
             "Hide the same indexes instead of dropping them (reversible)")):
        L = [head.format(title=title, n=len(drop), nk=sum(1 for _, w, _ in keep
                                                          if "read" not in w[0]),
                         sc=", ".join("SF=" + s for s in scales),
                         src=", ".join(os.path.basename(p) for p in paths))]
        last = None
        for (tbl, name), _, _ in sorted(drop):
            if tbl != last:
                L.append(f"\n-- {tbl}")
                last = tbl
            L.append(stmt.format(t=tbl, i=name))
        open(f"{REPO}/sql/{fname}", "w").write("\n".join(L) + "\n")
        print(f"  wrote sql/{fname}")

    L = ["-- Make every index visible to the optimizer again.",
         "-- Generated by scripts/decide-indexes.py.", ""]
    last = None
    for (tbl, name) in sorted(seen):
        if tbl != last:
            L.append(f"\n-- {tbl}")
            last = tbl
        L.append(f"ALTER TABLE {tbl} ALTER INDEX {name} NOT IGNORED;")
    open(f"{REPO}/sql/unignore_all_indexes.sql", "w").write("\n".join(L) + "\n")
    print("  wrote sql/unignore_all_indexes.sql")

    md = [f"# Index decisions\n",
          "An index is dropped if no scale factor reads it and no plan at any",
          "scale mentions it — or if hiding it measurably makes a query faster.\n",
          "Generated by `scripts/decide-indexes.py`. An index is kept if any",
          "scale factor read it **or** mentioned it in a plan.\n",
          f"- **keep {len(keep)}** ({gb(keep):.2f} GB)",
          f"- **drop {len(drop)}** ({gb(drop):.2f} GB)\n",
          "## Dropped\n",
          "| table | index | MB | why |", "|---|---|---:|---|"]
    for (tbl, name), why, _ in sorted(drop, key=lambda r: -size.get(r[0], 0)):
        reason = why[0] if why else "never read, never mentioned in any plan"
        md.append(f"| {tbl} | `{name}` | {size[(tbl, name)]:.1f} | {reason} |")
    md += ["", "## Kept — and why\n",
           "Most of these are never read. They are kept because the optimizer",
           "weighs them when costing alternatives, which read counters cannot see.\n",
           "| table | index | MB | reason |",
           "|---|---|---:|---|"]
    for (tbl, name), why, _ in sorted(keep, key=lambda r: -size.get(r[0], 0)):
        md.append(f"| {tbl} | `{name}` | {size[(tbl, name)]:.1f} | {'; '.join(why)} |")
    open(f"{REPO}/analysis/index-decisions.md", "w").write("\n".join(md) + "\n")
    print("  wrote analysis/index-decisions.md")


if __name__ == "__main__":
    main(sys.argv[1:])
