#!/usr/bin/env python3
"""Turn the drop list into IGNORE / UN-IGNORE statements.

    python3 scripts/make-ignore-sql.py

Writes:
    sql/ignore_unused_indexes.sql     hide them from the optimizer
    sql/unignore_all_indexes.sql      make every index visible again

WHY THIS EXISTS.  Dropping the 129 indexes that no scale factor reads made
SF=4 three times slower (491.4s -> 1487.0s).  Two explanations fit:

  PLANNING.  The optimizer uses an index's existence and statistics to cost
  alternatives, even when it ends up reading a different one.  Remove them
  and it costs badly, so it picks worse plans.

  STORAGE.  129 indexes occupy 16.3 GB.  Dropping them changes what fits in
  the buffer pool and what the loader had to maintain.

ALTER TABLE ... ALTER INDEX ... IGNORED separates the two.  An ignored index
is invisible to the optimizer but still present on disk, still maintained,
still occupying its pages.  So:

  ignoring is as slow as dropping   -> the cause is PLANNING
  ignoring is as fast as the full set -> the cause is STORAGE

That distinction decides which indexes can safely go.  An index that is
never read but changes which plan gets chosen is earning its keep and has to
stay; an index that is neither read nor consulted is dead weight.

IGNORED is metadata-only and reverses in about 0.15s, so this costs a
statement per index and no rebuild.
"""
import os, re, sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = f"{REPO}/sql/drop_unused_indexes.sql"

HEAD = """-- {title}
--
-- Generated by scripts/make-ignore-sql.py from sql/drop_unused_indexes.sql.
-- {n} indexes: the ones no scale factor READ while running the 40 tier-4/5
-- queries with the full index set present.
--
-- An IGNORED index is invisible to the optimizer but still on disk and still
-- maintained.  Comparing an ignored run against a dropped run separates
-- "the optimizer needed it to plan" from "the storage was in the way".
--
-- Metadata only; reverses with sql/unignore_all_indexes.sql in about 0.15s
-- per index.
"""


def main():
    if not os.path.exists(SRC):
        sys.exit(f"missing {SRC} -- run scripts/prune-indexes.py first")
    pairs = []
    for line in open(SRC):
        m = re.match(r'DROP INDEX IF EXISTS (\w+) ON (\w+);', line.strip())
        if m:
            pairs.append((m.group(2), m.group(1)))
    if not pairs:
        sys.exit(f"no DROP statements found in {SRC}")

    for state, fname, title in (
            ("IGNORED", "ignore_unused_indexes.sql",
             "Hide the never-read indexes from the optimizer"),
            ("NOT IGNORED", "unignore_all_indexes.sql",
             "Make the never-read indexes visible to the optimizer again")):
        L = [HEAD.format(title=title, n=len(pairs))]
        last = None
        for tbl, idx in pairs:
            if tbl != last:
                L.append(f"\n-- {tbl}")
                last = tbl
            L.append(f"ALTER TABLE {tbl} ALTER INDEX {idx} {state};")
        L.append("")
        open(f"{REPO}/sql/{fname}", "w").write("\n".join(L))
        print(f"  sql/{fname}: {len(pairs)} indexes -> {state}")


if __name__ == "__main__":
    main()
